const out = {};
for (const [name, weights] of Object.entries(icons)) {
  for (const w of weights) {
    const file = w === 'regular' ? `${name}.svg` : `${name}-${w}.svg`;
    const svg = readFileSync(join(assets, w, file), 'utf8');
    const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    out[w === 'regular' ? name : `${name}:${w}`] = inner;
  }
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
writeFileSync(join(root, 'src/ui/phosphor.ts'),
  `// Generated by scripts/gen-icons.mjs from @phosphor-icons/core (MIT). Do not edit.\nexport const PH: Record<string, string> = {\n${body}\n};\n`);
