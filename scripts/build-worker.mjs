// Builds the scanner's worker (src/ui/scan/worker.ts) into public/scan/worker.js as one plain
// script, so it runs the same in the browser and in the Android app (whose bundle is transformed
// differently). Run after changing kernels.ts, detect.ts, orient.ts or worker.ts:
//   node scripts/build-worker.mjs
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'public/scan/worker.js');
mkdirSync(dirname(out), { recursive: true });
await build({
  entryPoints: [join(root, 'src/ui/scan/worker.ts')], outfile: out,
  bundle: true, format: 'iife', target: 'es2019', minify: true, legalComments: 'none',
});
const hash = createHash('sha256').update(readFileSync(out)).digest('hex').slice(0, 10);
writeFileSync(join(root, 'src/ui/scan/workerVersion.ts'),
  `// Generated by scripts/build-worker.mjs: changes with public/scan/worker.js (busts caches).\nexport const WORKER_VERSION = '${hash}';\n`);
console.log('public/scan/worker.js', readFileSync(out).length, 'bytes, version', hash);
