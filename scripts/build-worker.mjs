// Builds the scanner's workers (src/ui/scan/worker.ts → public/scan/worker.js, and the AI worker
// src/ui/scan/aiWorker.ts → public/scan/ai.js with onnxruntime-web's WebAssembly runtime next to it)
// as plain scripts, so they run the same in the browser and in the Android app (whose bundle is
// transformed differently). Run after changing kernels.ts, detect.ts, orient.ts, dewarp.ts or a worker:
//   node scripts/build-worker.mjs
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'public/scan/worker.js');
mkdirSync(dirname(out), { recursive: true });
await build({
  entryPoints: [join(root, 'src/ui/scan/worker.ts')], outfile: out,
  bundle: true, format: 'iife', target: 'es2019', minify: true, legalComments: 'none',
});
const ai = join(root, 'public/scan/ai.js');
await build({
  entryPoints: [join(root, 'src/ui/scan/aiWorker.ts')], outfile: ai,
  bundle: true, format: 'iife', target: 'es2020', minify: true, legalComments: 'none',
  // the runtime's own loader is not used: the engine hands the WebAssembly bytes over
  define: { 'import.meta.url': '"about:blank"' }, logLevel: 'error',
});
copyFileSync(join(root, 'node_modules/onnxruntime-web/dist/ort-wasm-simd-threaded.wasm'), join(root, 'public/scan/ort.wasm'));
const hash = createHash('sha256').update(readFileSync(out)).update(readFileSync(ai)).digest('hex').slice(0, 10);
writeFileSync(join(root, 'src/ui/scan/workerVersion.ts'),
  `// Generated by scripts/build-worker.mjs: changes with public/scan/worker.js (busts caches).\nexport const WORKER_VERSION = '${hash}';\n`);
console.log('public/scan/worker.js', readFileSync(out).length, 'bytes; ai.js', readFileSync(ai).length, 'bytes; version', hash);
